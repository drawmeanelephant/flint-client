/// Largest ELF image `flint release` will hash. The whole file is read through
/// the FS abstraction, so this is a hard cap (refusal `store_too_large`).
pub const max_elf_bytes: usize = 256 * 1024 * 1024;

const release_file_name = "release.go";

fn isAlnum(c: u8) bool {
    return (c >= 'a' and c <= 'z') or (c >= 'A' and c <= 'Z') or (c >= '0' and c <= '9');
}

/// App names must start alphanumeric and may contain `.`, `_`, `-` so the
/// rendered Go string literal needs no escaping.
fn validReleaseName(name: []const u8) bool {
    if (name.len == 0 or name.len > 64) return false;
    if (!isAlnum(name[0])) return false;
    for (name) |c| {
        if (!isAlnum(c) and c != '.' and c != '_' and c != '-') return false;
    }
    return true;
}

/// Versions are semver or date stamps; `+` covers semver build metadata.
fn validReleaseVersion(version: []const u8) bool {
    if (version.len == 0 or version.len > 64) return false;
    if (!isAlnum(version[0])) return false;
    for (version) |c| {
        if (!isAlnum(c) and c != '.' and c != '_' and c != '-' and c != '+') return false;
    }
    return true;
}

/// Manifest rows ride inside a Go string literal, so only printable ASCII
/// without `"` or `\` is accepted; anything else refuses `usage`.
fn validManifestRow(row: []const u8) bool {
    if (row.len > 256) return false;
    for (row) |c| {
        if (c < 0x20 or c > 0x7e or c == '"' or c == '\\') return false;
    }
    return true;
}

/// Renders the release-stream `release.go` (convention tracked in issue #48).
/// `elf_sha256_hex` must already be lowercase hex. The manifest row is an
/// apps.txt v2 row whose schema is owned by VirelaiOS; callers supply it via
/// `--manifest-row` or get the documented `<name> <version> <sha256>`
/// placeholder.
pub fn renderReleaseGo(
    allocator: Allocator,
    name: []const u8,
    version: []const u8,
    elf_sha256_hex: []const u8,
    manifest_row: []const u8,
) ![]u8 {
    return std.fmt.allocPrint(allocator,
        \\// Code generated by "flint release"; DO NOT EDIT.
        \\//
        \\// Release-stream convention: release.go is tracked on the release
        \\// stream so verifiers can hash atoms instead of trusting prose.
        \\// ReleaseManifestRow is an apps.txt v2 row; the schema is owned by
        \\// VirelaiOS, and the default below is the documented
        \\// "<name> <version> <elf sha256>" placeholder from `flint release`
        \\// (override with --manifest-row).
        \\
        \\package release
        \\
        \\const ReleaseName = "{s}"
        \\const ReleaseVersion = "{s}"
        \\const ReleaseELFSHA256 = "{s}"
        \\const ReleaseManifestRow = "{s}"
        \\
    , .{ name, version, elf_sha256_hex, manifest_row });
}

/// Implements `flint release --elf=<f> --name=<n> --version=<v>
/// [--manifest-row=<r>] [--ws=<n>] [--key=<k>] [-m <msg>] [--dry-run]`.
///
/// Computes sha256(<elf>), renders release.go, writes it to the workspace src
/// root, then reuses `flint add`/`flint commit` to mint the signed Change on
/// the workspace's stream (no new signature surface). `--dry-run` prints the
/// rendered file and touches nothing — not even the store root.
pub fn cmdRelease(
    allocator: Allocator,
    fs: FS,
    store_flag: []const u8,
    env_flint_store: ?[]const u8,
    env_sign_key: ?[]const u8,
    cwd: []const u8,
    uuid_gen: *uuid.UUIDGen,
    out: *Io.Writer,
    args: []const []const u8,
) !void {
    var elf_arg: []const u8 = "";
    var name: []const u8 = "";
    var version: []const u8 = "";
    var manifest_row: []const u8 = "";
    var has_manifest_row = false;
    var ws_flag: []const u8 = "";
    var key_flag: []const u8 = "";
    var msg: []const u8 = "";
    var dry_run = false;

    var i: usize = 0;
    while (i < args.len) : (i += 1) {
        const a = args[i];
        if (std.mem.startsWith(u8, a, "--elf=")) {
            elf_arg = a["--elf=".len..];
        } else if (std.mem.eql(u8, a, "--elf") and i + 1 < args.len) {
            i += 1;
            elf_arg = args[i];
        } else if (std.mem.startsWith(u8, a, "--name=")) {
            name = a["--name=".len..];
        } else if (std.mem.eql(u8, a, "--name") and i + 1 < args.len) {
            i += 1;
            name = args[i];
        } else if (std.mem.startsWith(u8, a, "--version=")) {
            version = a["--version=".len..];
        } else if (std.mem.eql(u8, a, "--version") and i + 1 < args.len) {
            i += 1;
            version = args[i];
        } else if (std.mem.startsWith(u8, a, "--manifest-row=")) {
            manifest_row = a["--manifest-row=".len..];
            has_manifest_row = true;
        } else if (std.mem.eql(u8, a, "--manifest-row") and i + 1 < args.len) {
            i += 1;
            manifest_row = args[i];
            has_manifest_row = true;
        } else if (std.mem.startsWith(u8, a, "--ws=")) {
            ws_flag = a["--ws=".len..];
        } else if (std.mem.eql(u8, a, "--ws") and i + 1 < args.len) {
            i += 1;
            ws_flag = args[i];
        } else if (std.mem.startsWith(u8, a, "--key=")) {
            key_flag = a["--key=".len..];
        } else if (std.mem.eql(u8, a, "--key") and i + 1 < args.len) {
            i += 1;
            key_flag = args[i];
        } else if (std.mem.eql(u8, a, "-m") or std.mem.eql(u8, a, "--message")) {
            if (i + 1 >= args.len) {
                return fsys.refuse("usage", "");
            }
            i += 1;
            msg = args[i];
        } else if (std.mem.startsWith(u8, a, "-m=")) {
            msg = a["-m=".len..];
        } else if (std.mem.startsWith(u8, a, "--message=")) {
            msg = a["--message=".len..];
        } else if (std.mem.eql(u8, a, "--dry-run")) {
            dry_run = true;
        } else {
            return fsys.refuse("usage", "");
        }
    }

    if (elf_arg.len == 0 or !validReleaseName(name) or !validReleaseVersion(version) or
        (has_manifest_row and !validManifestRow(manifest_row)))
    {
        return fsys.refuse("usage", "");
    }

    const elf_path = try fsys.cleanPath(allocator, elf_arg);
    defer allocator.free(elf_path);

    const elf_bytes = fs.readFile(allocator, elf_path, max_elf_bytes) catch |err| switch (err) {
        error.FileNotFound, error.IsDir, error.NotDir => return fsys.refuse("src_missing", elf_path),
        else => return err,
    };
    defer allocator.free(elf_bytes);

    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(elf_bytes, &digest, .{});
    const elf_hex = std.fmt.bytesToHex(digest, .lower);

    var row_alloc: ?[]u8 = null;
    defer if (row_alloc) |r| allocator.free(r);
    if (!has_manifest_row) {
        row_alloc = try std.fmt.allocPrint(allocator, "{s} {s} {s}", .{ name, version, &elf_hex });
        manifest_row = row_alloc.?;
    }

    const rendered = try renderReleaseGo(allocator, name, version, &elf_hex, manifest_row);
    defer allocator.free(rendered);

    if (dry_run) {
        try out.writeAll(rendered);
        return;
    }

    const root = try store.resolveStoreRoot(allocator, fs, store_flag, env_flint_store, cwd);
    defer allocator.free(root);

    var idx = try store.loadStoreIndex(allocator, fs, root);
    defer idx.deinit();

    const ws = try store.resolveWorkspace(allocator, fs, &idx, ws_flag, &.{});

    // A release Change should contain exactly the release.go update; refuse a
    // dirty stage rather than folding unrelated staged Ops into it.
    const stage = try store.loadWorkspaceStage(allocator, fs, root, ws.name);
    defer store.freeOps(allocator, stage);
    if (stage.len > 0) {
        return fsys.refuse("stage_dirty", "");
    }

    const release_path = try fsys.joinPath(allocator, &.{ ws.src, release_file_name });
    defer allocator.free(release_path);
    try fs.writeFileSafe(allocator, release_path, rendered);

    const ws_arg = try std.fmt.allocPrint(allocator, "--ws={s}", .{ws.name});
    defer allocator.free(ws_arg);

    try workspace.cmdAdd(allocator, fs, root, uuid_gen, out, &.{ ws_arg, release_path });

    var msg_alloc: ?[]u8 = null;
    defer if (msg_alloc) |m| allocator.free(m);
    if (msg.len == 0) {
        msg_alloc = try std.fmt.allocPrint(allocator, "release {s} {s}", .{ name, version });
        msg = msg_alloc.?;
    }
    const msg_arg = try std.fmt.allocPrint(allocator, "--message={s}", .{msg});
    defer allocator.free(msg_arg);

    var commit_args: std.ArrayList([]const u8) = .empty;
    defer commit_args.deinit(allocator);
    try commit_args.append(allocator, ws_arg);
    try commit_args.append(allocator, msg_arg);

    var key_arg: ?[]u8 = null;
    defer if (key_arg) |k| allocator.free(k);
    if (key_flag.len > 0) {
        key_arg = try std.fmt.allocPrint(allocator, "--key={s}", .{key_flag});
        try commit_args.append(allocator, key_arg.?);
    }

    try sign.cmdCommit(allocator, fs, root, cwd, uuid_gen, env_sign_key, out, commit_args.items);

    try out.print("flint: release ok name={s} version={s} sha256={s}\n", .{ name, version, &elf_hex });
}

const TestClock = struct {
    now: i64 = 1760000000,
    rng: u8 = 1,

    fn getNow(ptr: ?*anyopaque) i64 {
        const self: *TestClock = @ptrCast(@alignCast(ptr.?));
        return self.now;
    }

    fn fillRand(ptr: ?*anyopaque, buf: []u8) void {
        const self: *TestClock = @ptrCast(@alignCast(ptr.?));
        for (buf) |*b| {
            b.* = self.rng;
            self.rng = self.rng *% 31 +% 17;
        }
    }
};

const ReleaseTestSetup = struct {
    mem: fsys.MemFS,
    clock: TestClock,
    gen: uuid.UUIDGen,

    fn init(allocator: Allocator) !ReleaseTestSetup {
        return .{
            .mem = try fsys.MemFS.init(allocator),
            .clock = .{},
            .gen = undefined,
        };
    }

    fn uuidGen(self: *ReleaseTestSetup) *uuid.UUIDGen {
        self.gen = uuid.UUIDGen.initCustom(&self.clock, TestClock.getNow, &self.clock, TestClock.fillRand);
        return &self.gen;
    }
};

fn sha256Hex(bytes: []const u8) [64]u8 {
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    return std.fmt.bytesToHex(digest, .lower);
}

