test "release: dry-run prints rendered release.go and touches nothing" {
    const gpa = std.testing.allocator;
    var setup = try ReleaseTestSetup.init(gpa);
    defer setup.mem.deinit();
    const fs = setup.mem.fs();

    try fs.writeFileSafe(gpa, "/host/bin/app.elf", "fake elf bytes");

    var out_w: Io.Writer.Allocating = .init(gpa);
    defer out_w.deinit();

    try cmdRelease(
        gpa,
        fs,
        "",
        null,
        null,
        "/host",
        setup.uuidGen(),
        &out_w.writer,
        &.{ "--elf=/host/bin/app.elf", "--name=virelaios-shell", "--version=1.2.3", "--dry-run" },
    );

    const elf_hex = sha256Hex("fake elf bytes");
    const expected_row = try std.fmt.allocPrint(gpa, "virelaios-shell 1.2.3 {s}", .{&elf_hex});
    defer gpa.free(expected_row);
    const expected = try renderReleaseGo(gpa, "virelaios-shell", "1.2.3", &elf_hex, expected_row);
    defer gpa.free(expected);
    try std.testing.expectEqualStrings(expected, out_w.written());

    // Dry-run must not write release.go or require a store.
    try std.testing.expect(!fs.exists(gpa, "/host/src/release.go"));
    try std.testing.expect(!fs.exists(gpa, "/host/FLINT"));
}

test "release: mints signed change with release.go atoms on workspace stream" {
    const gpa = std.testing.allocator;
    var setup = try ReleaseTestSetup.init(gpa);
    defer setup.mem.deinit();
    const fs = setup.mem.fs();
    const root = "/host/FLINT";

    try fs.mkdir(gpa, "/host/src");
    try fs.writeFileSafe(gpa, "/host/bin/app.elf", "fake elf bytes");

    var sink: Io.Writer.Allocating = .init(gpa);
    defer sink.deinit();
    try workspace.cmdInit(gpa, fs, root, setup.uuidGen(), &sink.writer, &.{ "--name=rel", "--src=/host/src" });
    try ed25519.cmdKeygen(gpa, fs, root, setup.uuidGen(), &.{"--name=maintainer"}, &sink.writer);

    var out_w: Io.Writer.Allocating = .init(gpa);
    defer out_w.deinit();

    try cmdRelease(
        gpa,
        fs,
        root,
        null,
        null,
        "/host",
        setup.uuidGen(),
        &out_w.writer,
        &.{ "--elf=/host/bin/app.elf", "--name=virelaios-shell", "--version=1.2.3" },
    );

    const elf_hex = sha256Hex("fake elf bytes");
    const written = try fs.readFile(gpa, "/host/src/release.go", store.MaxFileReadBytes);
    defer gpa.free(written);
    try std.testing.expect(std.mem.indexOf(u8, written, "const ReleaseName = \"virelaios-shell\"") != null);
    const want_hash_line = try std.fmt.allocPrint(gpa, "const ReleaseELFSHA256 = \"{s}\"", .{&elf_hex});
    defer gpa.free(want_hash_line);
    try std.testing.expect(std.mem.indexOf(u8, written, want_hash_line) != null);

    // The stage was consumed by the release commit.
    const stage_path = try store.workspaceStagePath(gpa, root, "rel");
    defer gpa.free(stage_path);
    try std.testing.expect(!fs.exists(gpa, stage_path));

    // One signed Change carrying the four const atoms now heads the stream.
    var idx = try store.loadStoreIndex(gpa, fs, root);
    defer idx.deinit();
    const st = idx.streamByName("main").?;
    try std.testing.expect(st.head != null);

    const atoms = try store.loadWorkspaceAtoms(gpa, fs, root, "rel");
    defer store.freeStoredAtoms(gpa, atoms);
    try std.testing.expectEqual(@as(usize, 4), atoms.len);
    for (atoms) |a| {
        try std.testing.expectEqualStrings("release.go", a.span.file);
        try std.testing.expectEqualStrings("const", a.kind);
    }
}

