test "release: refuses usage on missing or invalid inputs" {
    const gpa = std.testing.allocator;
    var setup = try ReleaseTestSetup.init(gpa);
    defer setup.mem.deinit();
    const fs = setup.mem.fs();

    try fs.writeFileSafe(gpa, "/host/bin/app.elf", "fake elf bytes");

    var out_w: Io.Writer.Allocating = .init(gpa);
    defer out_w.deinit();

    const cases = [_][]const []const u8{
        &.{ "--elf=/host/bin/app.elf", "--version=1.0.0" }, // no --name
        &.{ "--elf=/host/bin/app.elf", "--name=app" }, // no --version
        &.{ "--name=app", "--version=1.0.0" }, // no --elf
        &.{ "--elf=/host/bin/app.elf", "--name=bad name", "--version=1.0.0" },
        &.{ "--elf=/host/bin/app.elf", "--name=app", "--version=1.0.0\"" },
        &.{ "--elf=/host/bin/app.elf", "--name=app", "--version=1.0.0", "--manifest-row=a\"b" },
        &.{ "--elf=/host/bin/app.elf", "--name=app", "--version=1.0.0", "--bogus" },
    };
    for (cases) |args| {
        const err = cmdRelease(gpa, fs, "", null, null, "/host", setup.uuidGen(), &out_w.writer, args);
        try std.testing.expectError(error.Refuse, err);
        try std.testing.expectEqualStrings("usage", fsys.last_refuse.code());
    }
    try std.testing.expectEqual(@as(usize, 0), out_w.written().len);
}

test "release: refuses stage_dirty instead of folding unrelated staged ops" {
    const gpa = std.testing.allocator;
    var setup = try ReleaseTestSetup.init(gpa);
    defer setup.mem.deinit();
    const fs = setup.mem.fs();
    const root = "/host/FLINT";

    try fs.mkdir(gpa, "/host/src");
    try fs.writeFileSafe(gpa, "/host/bin/app.elf", "fake elf bytes");
    try fs.writeFileSafe(gpa, "/host/src/other.go", "package other\n\nconst Other = 1\n");

    var sink: Io.Writer.Allocating = .init(gpa);
    defer sink.deinit();
    try workspace.cmdInit(gpa, fs, root, setup.uuidGen(), &sink.writer, &.{ "--name=rel", "--src=/host/src" });
    try workspace.cmdAdd(gpa, fs, root, setup.uuidGen(), &sink.writer, &.{"--ws=rel"});

    var out_w: Io.Writer.Allocating = .init(gpa);
    defer out_w.deinit();

    const err = cmdRelease(
        gpa,
        fs,
        root,
        null,
        null,
        "/host",
        setup.uuidGen(),
        &out_w.writer,
        &.{ "--elf=/host/bin/app.elf", "--name=app", "--version=1.0.0" },
    );
    try std.testing.expectError(error.Refuse, err);
    try std.testing.expectEqualStrings("stage_dirty", fsys.last_refuse.code());
    try std.testing.expect(!fs.exists(gpa, "/host/src/release.go"));
}
